export type PracticeTestModuleId = 'tmas1' | 'tmas2' | 'tmas3' | 'ld152016'

export type PracticeTestQuestion = {
  id: string
  ldNumber: string
  ttsRefs: string[]
  objective: string
  prompt: string
  choices: string[]
  correctIndex: number
  explanation: string
  format?: 'multiple_choice' | 'true_false'
}

export type PracticeTestScenario = {
  id: string
  title: string
  stem: string
  ldNumbers: string[]
  questions: PracticeTestQuestion[]
}

export type PracticeTestModule = {
  id: PracticeTestModuleId
  title: string
  status: 'available' | 'coming_soon'
  description: string
  formatSummary: string
  officialBasis: string[]
  formatSignals: string[]
  scenarios: PracticeTestScenario[]
}

function question(
  id: string,
  ldNumber: string,
  objective: string,
  prompt: string,
  choices: string[],
  correctIndex: number,
  explanation: string,
): PracticeTestQuestion {
  return {
    id,
    ldNumber,
    ttsRefs: resolvePracticeTestTtsRefs(ldNumber, objective),
    objective,
    prompt,
    choices,
    correctIndex,
    explanation,
  }
}

function scenario(
  id: string,
  title: string,
  stem: string,
  ldNumbers: string[],
  questions: PracticeTestQuestion[],
): PracticeTestScenario {
  return {
    id,
    title,
    stem,
    ldNumbers,
    questions,
  }
}

