import { resolvePracticeTestTtsRefs } from './practiceTestTtsRefs'

type PracticeTestQuestion = {
  id: string
  ldNumber: string
  ttsRefs: string[]
  objective: string
  prompt: string
  choices: string[]
  correctIndex: number
  explanation: string
  format?: 'multiple_choice' | 'true_false'
}

type PracticeTestScenario = {
  id: string
  title: string
  stem: string
  ldNumbers: string[]
  questions: PracticeTestQuestion[]
}

function tts(refs: string[], summary: string) {
  return `TTS ${refs.join(' / ')} — ${summary}`
}

function question(
  id: string,
  ldNumber: string,
  objective: string,
  prompt: string,
  choices: string[],
  correctIndex: number,
  explanation: string,
): PracticeTestQuestion {
  return {
    id,
    ldNumber,
    ttsRefs: resolvePracticeTestTtsRefs(ldNumber, objective),
    objective,
    prompt,
    choices,
    correctIndex,
    explanation,
  }
}

function scenario(
  id: string,
  title: string,
  stem: string,
  ldNumbers: string[],
  questions: PracticeTestQuestion[],
): PracticeTestScenario {
  return { id, title, stem, ldNumbers, questions }
}

